// AI-assisted (Claude Code): turns Hipo's university-domains-list JSON into a repeatable SQL migration for public.institutions (upsert on name + country).
// Usage:
//   curl -sL https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json -o /tmp/universities.json
//   node scripts/import-institutions.mjs /tmp/universities.json   → writes supabase/migrations/<timestamp>_seed_institutions.sql
// Licence: MIT, copyright Hipo; the notice is kept in supabase/seed/LICENSE-university-domains-list.txt.
import { readFileSync, writeFileSync } from "node:fs";

const path = process.argv[2];
if (!path) {
  console.error("Usage: node scripts/import-institutions.mjs <world_universities_and_domains.json>");
  process.exit(1);
}

// Same normalization as normalizeForSearch in src/countries.ts: no accents, lowercase.
function normalize(value) {
  return value.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();
}

function literal(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

const list = JSON.parse(readFileSync(path, "utf8"));
if (!Array.isArray(list)) {
  console.error("Expected a JSON array of universities.");
  process.exit(1);
}

// One row per name + country; rows without a valid name or ISO alpha-2 code are skipped and counted.
const rows = new Map();
let skipped = 0;
for (const item of list) {
  const name = typeof item?.name === "string" ? item.name.replace(/\s+/g, " ").trim() : "";
  const country = typeof item?.alpha_two_code === "string" ? item.alpha_two_code.trim().toUpperCase() : "";
  if (!name || !/^[A-Z]{2}$/.test(country)) {
    skipped++;
    continue;
  }
  rows.set(`${name}|${country}`, { name, country });
}
const sorted = [...rows.values()].sort((a, b) => a.country.localeCompare(b.country) || a.name.localeCompare(b.name));

const values = sorted.map((row) => `  (${literal(row.name)}, ${literal(row.country)}, ${literal(normalize(row.name))})`).join(",\n");

const sql = `-- AI-assisted (Claude Code): generated by scripts/import-institutions.mjs from Hipo's university-domains-list (MIT licence). Do not edit by hand.
-- ${sorted.length} institutions (${list.length - sorted.length - skipped} duplicates and ${skipped} invalid rows left out). Repeatable: upsert on name + country.

insert into public.institutions (name, country, search_name)
values
${values}
on conflict (name, country) do update
  set search_name = excluded.search_name;
`;

const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const file = `supabase/migrations/${stamp}_seed_institutions.sql`;
writeFileSync(file, sql);
console.log(`${file}: ${sorted.length} institutions, ${list.length - sorted.length - skipped} duplicates, ${skipped} invalid`);
